export default function Icon({ name, size = 16, strokeWidth = 1.75, className = '', title, ...rest }) {
  const glyph = paths[name];
  if (!glyph) {
    // Returning null here used to leave an empty button on screen — the sidebar
    // collapse control rendered as a blank square for exactly this reason. Warn
    // loudly, and in development draw a placeholder so the gap is visible.
    console.warn(`<Icon> unknown name: "${name}" — nothing will be drawn.`);
    if (!import.meta.env.DEV) return null;
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={strokeWidth} aria-hidden="true">
        <rect x="3" y="3" width="18" height="18" rx="3" strokeDasharray="3 2" />
        <line x1="8" y1="8" x2="16" y2="16" />
        <line x1="16" y1="8" x2="8" y2="16" />
      </svg>
    );
  }
  return (
    <svg
      className={`icon${className ? ` ${className}` : ''}`}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={title ? undefined : 'true'}
      role={title ? 'img' : undefined}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {glyph}
    </svg>
  );
}
